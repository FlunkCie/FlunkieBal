/// Width of `text` in grid units (6 per character including the gap).
pub fn width(text: &str) -> f32 {
    text.chars().count() as f32 * 6.0 - 2.0
}

/// Write `text` on a surface. `frame` maps the surface plane: x right, y up, z out of the surface (metres).
/// `h` is the cap height in metres; `at` is the bottom-left corner in the frame.
pub fn write(dl: &mut DrawList, frame: Mat4, at: (f32, f32), h: f32, text: &str, color: [f32; 3]) {
    let u = h / 6.0;
    let th = (u * 0.55).max(0.004);
    let mut x0 = at.0;
    for c in text.to_uppercase().chars() {
        for stroke in glyph(c) {
            for w in stroke.windows(2) {
                let a = vec3(x0 + w[0].0 * u, at.1 + w[0].1 * u, 0.0);
                let b = vec3(x0 + w[1].0 * u, at.1 + w[1].1 * u, 0.0);
                let d = b - a;
                let len = d.length() + th;
                let ang = d.y.atan2(d.x);
                let m = frame * Mat4::from_translation((a + b) * 0.5) * Mat4::from_quat(Quat::from_rotation_z(ang)) * Mat4::from_scale(vec3(len, th, 0.002));
                dl.push(Mesh::Cube, m, [color[0], color[1], color[2], 1.0], [kind::UNLIT, 0.0, 0.0, 1.0]);
            }
        }
        x0 += 6.0 * u;
    }
}

/// Where text of a given cap height ends, for right-aligning.
pub fn right_aligned_x(right: f32, h: f32, text: &str) -> f32 {
    right - width(text) * h / 6.0
}

#[allow(dead_code)]
pub fn origin() -> Vec3 {
    Vec3::ZERO
}
